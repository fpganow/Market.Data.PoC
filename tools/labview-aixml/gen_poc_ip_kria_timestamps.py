#!/usr/bin/env python3
"""AIXML for fpga/poc.ip.kria.generated.vi - a REFERENCE snippet for todo.txt item 10.

poc.ip.kria.vi itself cannot be regenerated (its FIFO/Register/Timed Loop nodes do not
survive the AIXML round trip), so this VI reproduces only the timestamp logic of the
156.25 MHz "PoC IP" loop, with the recommended change in place and comment boxes that say
where it goes.  It runs under My Computer: a For Loop stands in for the Timed Loop, one
iteration = one 156.25 MHz cycle, inputs/outputs are auto-indexed arrays so one run shows
the behaviour over a sequence of cycles.

    python3 gen_poc_ip_kria_timestamps.py poc.ip.kria.timestamps.xml
"""
import sys

def esc(s):
    """AIXML attribute text: \\3A colon, \\2C comma, \\0A newline, then XML entities."""
    s = s.replace('\\', '\\\\').replace(':', '\\3A').replace(',', '\\2C').replace('\n', '\\0A')
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('"', '&quot;')

DESC = (
    "REFERENCE ONLY - todo.txt item 10 (recv.time / parse.time). poc.ip.kria.vi cannot be "
    "regenerated by the AIXML tools (FIFO, Register and Timed Loop nodes are lost), so this VI "
    "shows the timestamp logic of the 156.25 MHz 'PoC IP' Timed Loop with the recommended change "
    "already made. Copy the nodes between the comment boxes into poc.ip.kria.vi; do not replace "
    "the VI.\n\n"
    "FACTS established 2026-10-11 from the AIXML export of poc.ip.kria.vi and the netlist sim of "
    "the 19:37 IP export:\n"
    "1. The tick counter (Feedback Node -> Increment -> Select, reset on the ip.reset rising edge) "
    "lives in the 156.25 MHz loop together with TDATA/TVALID/ip.reset. One tick = one 156.25 MHz "
    "cycle = 6.4 ns, NOT 10 ns (sim: recv.time advances exactly one count per input beat). Every "
    "latency figure quoted so far with 10 ns/tick is 1.56x too large.\n"
    "2. bats.parser.vi runs in the OTHER Timed Loop (100 MHz, with the CMD/DEBUG outputs). Its "
    "`time` input comes from a Register read; the Register (written with the counter every cycle "
    "in the 156 MHz loop) IS the clock-domain crossing. A wire from the counter to the parser is "
    "impossible between two Timed Loops, so the register read STAYS. Its lag (1-3 ticks, 6-19 ns) "
    "is the price of the crossing; parse.time is therefore a few ticks late, never early.\n"
    "3. Today recv.time is wired straight from the counter into the stream cluster that enters "
    "the CDC FIFO, so each CMD record carries the arrival tick of the word that completed its "
    "message (per-word stamp). The frame-start latch that existed before 2026-10-11 is gone.\n\n"
    "RECOMMENDED CHANGE (the only diagram change): put the frame-start latch back, i.e. "
    "recv.time := counter when `data valid` rises (first word of a frame), else hold the previous "
    "value. Then parse.time - recv.time is 'time since the first byte of the packet arrived', the "
    "quantity a trading system cares about, the figure is comparable with the earlier measurements, "
    "and the host tools can group a frame's records by equal recv.time. The latch is the Not / "
    "Feedback Node / And / Select / Feedback Node group in the box 'CHANGE - frame-start latch'.\n\n"
    "ALTERNATIVE (no diagram change): keep the per-word stamp. Then parse.time - recv.time is the "
    "parser's own per-message latency (1 tick for a message completed by the arriving word, more "
    "for messages queued behind it) and Claude switches eval_sim.py / decode_capture.py to group "
    "by sequence number. Tell Claude which one you chose.\n\n"
    "HOST SIDE (Claude does this): TICK_NS 10 -> 6.4 in apps/poc_inject/decode_capture.py and "
    "ip_export/netlist_sim/eval_sim.py; CLAUDE.md latency figures re-stated in 6.4 ns ticks.\n\n"
    "Run this VI: ip.reset = [T,F,F,...], data valid = [F,F,T,T,T,F,F,T,T,F]. Expect tick = "
    "0,1,2,...; first word of frame = T at indexes 2 and 7; recv.time = 0,0,2,2,2,2,2,7,7,7."
)

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'poc.ip.kria.timestamps.xml'
    L = []
    a = L.append
    a(f'<VI _name="poc.ip.kria.generated.vi" description="{esc(DESC)}">')
    # front panel: one array element per 156.25 MHz cycle
    a('  <Control _name="ip.reset" conIdx="11" connection="recommended" type="array{bool}" uid="10" uid_parent="root" value="[true,false,false,false,false,false,false,false,false,false]" outputs="value:10.value"/>')
    a('  <Control _name="data valid" conIdx="10" connection="recommended" type="array{bool}" uid="11" uid_parent="root" value="[false,false,true,true,true,false,false,true,true,false]" outputs="value:11.value"/>')
    a(f'  <FreeLabel comment="{esc("REFERENCE SNIPPET for todo item 10 - read the VI description (Ctrl-I).\nOne loop iteration = one cycle of the 156.25 MHz PoC IP Timed Loop in poc.ip.kria.vi.\nInputs/outputs are arrays only so the VI can be run on My Computer; in poc.ip.kria.vi they are the plain wires named in the boxes.")}" uid="12" uid_parent="root"/>')
    a('  <Structure _name="For Loop" count="" maxin="" maxout="" uid="100" uid_parent="root">')
    a('    <Tunnel _id="In1" inputs="value:10.value" mode="index" outputs="value:101.reset" uid="101" uid_parent="100"/>')
    a('    <Tunnel _id="In2" inputs="value:11.value" mode="index" outputs="value:102.valid" uid="102" uid_parent="100"/>')
    # --- counter (unchanged) ---
    a(f'    <FreeLabel comment="{esc("UNCHANGED - tick counter as it is in poc.ip.kria.vi (156.25 MHz loop):\nFeedback Node -> Increment -> Select (t = 0, s = ip.reset rising edge, f = x+1).\nOne tick = 6.4 ns. Keep the Register WRITE of this wire: it is the clock-domain crossing\nthat bats.parser.vi (100 MHz loop) reads as `time`. That Register read cannot be replaced by a wire.")}" uid="103" uid_parent="100"/>')
    a('    <Constant _name="0" type="uint64" uid="110" uid_parent="100" value="0" outputs="value:110.value"/>')
    a('    <Node _name="Feedback Node" comment="tick" inputs="initializer:,next value:120.tick" outputs="previous value:111.prev" uid="111" uid_parent="100"/>')
    a('    <Node _name="Increment" inputs="x:111.prev" outputs="x+1:112.inc" uid="112" uid_parent="100"/>')
    a('    <Node _name="Select" comment="tick counter" inputs="t:110.value,s:101.reset,f:112.inc" outputs="s? t\\3Af:120.tick" uid="113" uid_parent="100"/>')
    # --- change: frame-start latch ---
    a(f'    <FreeLabel comment="{esc("CHANGE - frame-start latch (insert between the counter wire and the Bundle By Name\nthat writes recv.time into My.Network.Data.Stream, right before the CDC FIFO write):\nfirst word = data valid AND NOT Feedback(data valid)\nrecv.time  = first word ? counter : Feedback(recv.time)\nToday recv.time is wired straight from the counter (per-word stamp).")}" uid="104" uid_parent="100"/>')
    a('    <Node _name="Feedback Node" comment="previous data valid" inputs="initializer:,next value:102.valid" outputs="previous value:114.prevvalid" uid="114" uid_parent="100"/>')
    a('    <Node _name="Not" inputs="x:114.prevvalid" outputs=".not. x?:115.notprev" uid="115" uid_parent="100"/>')
    a('    <Node _name="And" comment="first word of frame" inputs="x:102.valid,y:115.notprev" outputs="x .and. y?:116.first" uid="116" uid_parent="100"/>')
    a('    <Node _name="Feedback Node" comment="previous recv.time" inputs="initializer:,next value:130.recv" outputs="previous value:117.prevrecv" uid="117" uid_parent="100"/>')
    a('    <Node _name="Select" comment="recv.time latch" inputs="t:120.tick,s:116.first,f:117.prevrecv" outputs="s? t\\3Af:130.recv" uid="118" uid_parent="100"/>')
    a(f'    <FreeLabel comment="{esc("-> recv.time element of the My.Network.Data.Stream Bundle By Name (CDC FIFO write).\nAfter the change every record of a frame carries the arrival tick of the frame's first word.\nALTERNATIVE: leave poc.ip.kria.vi as it is (per-word stamp) and tell Claude to switch the host grouping.")}" uid="105" uid_parent="100"/>')
    a('    <Tunnel _id="Out1" inputs="value:120.tick" mode="index" outputs="value:141.ticks" uid="141" uid_parent="100"/>')
    a('    <Tunnel _id="Out2" inputs="value:130.recv" mode="index" outputs="value:142.recvs" uid="142" uid_parent="100"/>')
    a('    <Tunnel _id="Out3" inputs="value:116.first" mode="index" outputs="value:143.firsts" uid="143" uid_parent="100"/>')
    a('  </Structure>')
    a('  <Indicator _name="tick (counter wire -> Register write -> parser time)" conIdx="3" connection="recommended" type="array{uint64}" uid="20" uid_parent="root" value="[]" inputs="value:141.ticks"/>')
    a('  <Indicator _name="recv.time (-> stream bundle)" conIdx="2" connection="recommended" type="array{uint64}" uid="21" uid_parent="root" value="[]" inputs="value:142.recvs"/>')
    a('  <Indicator _name="first word of frame" conIdx="1" connection="recommended" type="array{bool}" uid="22" uid_parent="root" value="[]" inputs="value:143.firsts"/>')
    a('</VI>')
    open(out, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('wrote', out, len(L), 'lines')

if __name__ == '__main__':
    main()
